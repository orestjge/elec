/// 長押しでメニューを出すときの長さ。**入れ子になる長押しで揃える**ための置き場。
///
/// レス（`post_item.dart`）の中にはサムネイル（`post_images.dart`）が入っていて、
/// どちらも長押しでメニューを出す。入れ子の長押しは同じ土俵（[GestureArena]）で
/// 競り、**先に締め切りが来た方が勝つ**。外側だけ短くすると、内側の長押しは
/// いつまでも通らない。長さを揃えれば内側が勝つ——ポインタは内側から順に配られる
/// ので、待ち時間も内側から始まり、同時刻の締め切りなら先に手が挙がる。
library;

import 'package:flutter/widgets.dart';

/// 長押しがメニューに繋がるまでの時間。
///
/// 既定の 500ms は「押しているのに何も起きない」と感じる長さなので短くする。
/// タップの判定（100ms）とは十分離れているので、触れただけでメニューが出ることは
/// ない。
const menuLongPressDuration = Duration(milliseconds: 400);

/// 触れてから押している手応えを出し始めるまでの待ち時間。スクロールを始めるときの
/// 一瞬の接触でチカチカしないよう、指を止めている間だけ出す。
///
/// スクロールが確定するのは指が 18px 動いてからで、そこまでの時間は引き方次第。
/// この待ち時間だけでは防ぎきれないので、指が動いたかどうかも併せて見る
/// （[pressMoveSlop]）。
const pressFeedbackDelay = Duration(milliseconds: 150);

/// 指がこれだけ動いたらスワイプとみなして手応えを引っ込める距離。
///
/// 長押しの判定が外れる距離（`kTouchSlop` = 18px）を待つと、スクロールを始めた
/// 指の下で一瞬出てしまうので、その手前で引く。指の細かい揺れでは消えない程度には
/// 残す。
const pressMoveSlop = 8.0;

/// 内側の長押しがその押しを引き受けた、という外側への合図。
///
/// 押している間の手応えは、外側（レス）も内側（サムネイル）も**指の下**に出す。
/// 内側が引き受けたことを外側が知らないと、開くのはサムネイルのメニューなのに
/// レス全体が沈み込む——的の違うものが動いて見える。押し始め（引き受けた時点）に
/// 流すので、外側は手応えを出す前に降りられる。
class LongPressClaimed extends Notification {
  const LongPressClaimed({required this.pressed});

  /// 押している間は true、離した・外れたら false。
  final bool pressed;
}
